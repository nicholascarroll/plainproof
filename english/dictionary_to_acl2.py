#!/usr/bin/env python3
"""english/dictionary.pl -> acl2/dictionary-data.lisp, so the ACL2 compiler reads
the same dictionary as everything else.  One source of truth."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "english"))
from dictionary import load
kinds = load()
def sym(s): return s.upper() if s != "nil" else "NIL"
out = ["; GENERATED by english/dictionary_to_acl2.py from english/dictionary.pl. Do not edit.",
       '(in-package "ACL2")', ""]
def alist(name, rows, val):
    out.append(f"(defconst {name}\n  '(" + "\n    ".join(val(r) for r in rows) + "))\n")
alist("*type-nouns*", kinds["type_noun"], lambda r: f'("{r[0]}" . {sym(r[1])})')
alist("*result-nouns*", kinds["result_noun"], lambda r: f'("{r[0]}" {sym(r[1])} {r[2]})')
alist("*relation-nouns*", kinds["relation_noun"], lambda r: f'("{r[0]}" . {sym(r[1])})')
alist("*relation-adjectives*", kinds["relation_adjective"], lambda r: f'("{r[0]}" . {sym(r[1])})')
alist("*adjectives*", kinds["adjective"], lambda r: f'("{r[0]}" . {sym(r[1])})')
alist("*comparisons*", kinds["comparison"], lambda r: f'("{r[0]}" . {sym(r[1])})')
alist("*constants*", kinds["constant"], lambda r: f'("{r[0]}" . {sym(r[1])})')
open(os.path.join(ROOT, "acl2/dictionary-data.lisp"), "w").write("\n".join(out))
print("wrote acl2/dictionary-data.lisp")
